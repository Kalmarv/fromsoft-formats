#!/usr/bin/env python3
"""Generates src/flver/gx_items.rs: the community names of the words of the FLVER material extension items (GX items) that
Sekiro's and Elden Ring's models store.

Input: Smithbox's `GX_Item_Descriptors.json` (Smithbox fdde3225, MIT repository; the file carries no licence of its own and
is read as data: an item's id and version, and for each 4-byte word its name and a type code). Only the items the two
installs hold are generated (SEEN: the census over every FLVER of both installs, `tests/gx_census.rs`); the file names more
(GX01, GX02, GX08, GX12, GX13, GX28 to GX29, GX31, GX33 to GX37), none of which occurs in either install.

    python tools/gen_gx_items.py PATH/TO/GX_Item_Descriptors.json > src/flver/gx_items.rs

The descriptor's type codes: 0 a word it does not name ("Unknown"), 1 an integer, 2 a float, 3 and 4 integers the file
gives its own codes (the tessellation mode and the displacement and decal switches, whose stored values are 0 and 1).
"""
import json
import sys

SEEN = [("GX00", 100), ("GX00", 101), ("GX00", 102), ("GX03", 100), ("GX04", 100), ("GX05", 100), ("GX06", 101),
        ("GX07", 104), ("GX09", 100), ("GX14", 101), ("GX15", 100)] + \
       [(f"GX{n}", 100) for n in (20, 21, 22, 23, 24, 25, 26, 27, 30, 32, 39, 80, 81)]
KIND = {0: "Unknown", 1: "Int", 2: "Float", 3: "Choice", 4: "Flag"}


def main():
    items = {(x["ID"], x["Unk04"]): x for x in json.load(open(sys.argv[1], encoding="utf-8"))["list"]}
    out = ["// Generated by tools/gen_gx_items.py from Smithbox's GX_Item_Descriptors.json (Smithbox fdde3225); do not edit.",
           "use super::gx::{ItemInfo, WordInfo, WordKind::*};",
           "",
           "const fn w(name: &'static str, kind: super::gx::WordKind) -> WordInfo {",
           "    WordInfo { name, kind }",
           "}",
           "",
           "pub(super) const ITEMS: &[ItemInfo] = &["]
    for key in SEEN:
        x = items[key]
        words = ", ".join(f'w({json.dumps(i["Name"])}, {KIND[i["Type"]]})' for i in x["Items"])
        category = "None" if x["Category"] is None else f'Some({json.dumps(x["Category"])})'
        out.append(f"    ItemInfo {{ id: *b\"{key[0]}\", version: {key[1]}, category: {category}, words: &[{words}] }},")
    out.append("];")
    print("\n".join(out))


main()
