#!/usr/bin/env python3
"""Generates src/emedf/sekiro.rs and src/emedf/elden.rs: the instruction schema of the games' event scripts (EMEVD), from
the community's EMEDF files (the instruction and argument names and the argument types of each instruction).

    python tools/gen_emedf.py SEKIRO_EMEDF.json ELDEN_EMEDF.json src/emedf

The files are the DarkScript3 EMEDF format, as Smithbox ships it for Sekiro and as soulstruct ships it for Elden Ring (the
second holds the instructions later patches added). Only facts are taken from them: a name, a type number, an enum name.
Each instruction's argument layout is checked against every stock script by tests/emedf_census.rs; the roles (which
arguments are event flags, entity ids, map parts) are this crate's own, assigned from the argument names by the rules
below and checked on the stock scripts by the same census.

Type numbers: 0 u8, 1 u16, 2 u32, 3 i8, 4 i16, 5 i32, 6 f32, 8 a string-table offset (u32). Arguments sit at their natural
alignment and the block is padded to four bytes. The last argument of an instruction flagged `vararg` repeats.
"""
import json
import re
import sys

KINDS = {0: "U8", 1: "U16", 2: "U32", 3: "I8", 4: "I16", 5: "I32", 6: "F32", 8: "Text"}

# the event initialisers: the argument that names the called event, and the one that names its slot
EVENT_INITIALISERS = {(2000, 0), (2000, 1), (2000, 6)}


def role(game, bank, ins, name, ty, index):
    """The crate's role of an argument, from its name (see tests/emedf_census.rs for what holds on the stock scripts)."""
    if (bank, ins) in EVENT_INITIALISERS:
        if name == "Event ID":
            return "EventId"
        if name == "Event Slot ID" or (game == "elden" and (bank, ins) == (2000, 6) and index == 0):
            return "EventSlot"
    if re.search(r"Number of Used (Event )?Flag Bits|Left-side Number|Right-side Number", name):
        return "FlagBitCount"
    if "Base Event Flag ID" in name:
        return "FlagBase"
    if re.search(r"Event Flag ID|ObjAct Event Flag|Event Flag$", name) and not re.search(r"Type|State", name):
        return "Flag"
    if re.search(r"Entity (A |B )?ID|Entity ID \d|Entity ID to", name) and "Entity Type" not in name:
        return "Entity"
    if name == "Map ID" and ty == 5:
        return "MapWord"
    return {"Area ID": "MapArea", "Block ID": "MapBlock", "Region ID": "MapRegion", "Index ID": "MapIndex"}.get(
        name, "Other"
    )


def load(path):
    text = open(path, encoding="utf-8-sig").read()
    # the files carry commented-out blocks
    text = "\n".join(line for line in text.split("\n") if not line.lstrip().startswith("//"))
    out = {}
    for cls in json.loads(text)["main_classes"]:
        for ins in cls["instrs"]:
            key = (cls["index"], ins["index"])
            if key in out:
                raise SystemExit(f"{path}: instruction {key} is defined twice")
            out[key] = ins
    return out


def rust_string(s):
    return json.dumps(s, ensure_ascii=True)


def emit(game, path, instructions, out):
    w = out.append
    w(f"//! Generated by `tools/gen_emedf.py` from the community's EMEDF file for {game}. Do not edit.")
    w("//!")
    w("//! The instruction schema of the game's event scripts: each instruction's name and the name, type, enum name and role")
    w("//! of its arguments, by bank and number.")
    w("")
    w("use super::{ArgDef, ArgKind, InstructionDef, Role};")
    w("")
    w("macro_rules! a {")
    w("    ($name:expr, $kind:ident, $role:ident, $enum:expr) => {")
    w("        ArgDef { name: $name, kind: ArgKind::$kind, role: Role::$role, enum_name: $enum }")
    w("    };")
    w("}")
    w("")
    w("macro_rules! i {")
    w("    ($bank:expr, $id:expr, $name:expr, $vararg:expr, [$($arg:expr),* $(,)?]) => {")
    w("        InstructionDef { bank: $bank, id: $id, name: $name, vararg: $vararg, args: &[$($arg),*] }")
    w("    };")
    w("}")
    w("")
    w("/// The instructions, by bank and number.")
    w("pub(super) static INSTRUCTIONS: &[InstructionDef] = &[")
    for (bank, number) in sorted(instructions):
        ins = instructions[(bank, number)]
        args = ins["args"]
        vararg = any(a.get("vararg") for a in args)
        if vararg and not args[-1].get("vararg"):
            raise SystemExit(f"{path}: ({bank}, {number}): the repeating argument is not the last")
        parts = []
        for index, a in enumerate(args):
            ty = a["type"]
            if ty not in KINDS:
                raise SystemExit(f"{path}: ({bank}, {number}): unknown argument type {ty}")
            enum = a.get("enum_name")
            enum_text = f"Some({rust_string(enum)})" if enum else "None"
            parts.append(
                f"a!({rust_string(a['name'])}, {KINDS[ty]}, {role(game, bank, number, a['name'], ty, index)}, {enum_text})"
            )
        body = ", ".join(parts)
        w(
            f"    i!({bank}, {number}, {rust_string(ins['name'])}, {'true' if vararg else 'false'}, [{body}]),"
        )
    w("];")


def main(sekiro, elden, folder):
    for game, source in (("sekiro", sekiro), ("elden", elden)):
        out = []
        emit(game, source, load(source), out)
        with open(f"{folder}/{game}.rs", "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    main(*sys.argv[1:])
