#!/usr/bin/env python3
"""Generates src/fxr/enums.rs: the value sets the fxr project names for FXR parameters (blend modes, attachment modes,
orientation modes, emitter directions, node and config kinds, ...), from the project's built data
(`dist/enums.json` of EvenTorset/fxr, Unlicense).

    python tools/gen_fxr_enums.py PATH/TO/enums.json > src/fxr/enums.rs

Every enum has `value()` and `from_value()`; a value the project does not name is `None` from `from_value`, and the
census (tests/fxr_actions_census.rs) counts every value the installed files store against these sets.
"""
import json
import sys

SKIP = {"ActionType"}  # the action types are the typed structs


def main(path):
    data = json.load(open(path, encoding="utf-8"))
    out = []
    w = out.append
    w("//! Generated by `tools/gen_fxr_enums.py` from the fxr project's enum data (EvenTorset/fxr, Unlicense). Do not edit.")
    w("//!")
    w("//! The values the project names for FXR parameters. Some members are the project's own placeholders (`Unk6`) for a")
    w("//! value the files store and whose effect it has only guessed at; those names are kept as the project gives them.")
    w("")
    for name in sorted(data):
        if name in SKIP:
            continue
        e = data[name]
        members = sorted(e["members"].items(), key=lambda kv: kv[1]["value"])
        first_line = e["desc"]["en-US"].strip().splitlines()[0].replace("[", "").replace("]", "")
        # drop link targets
        import re
        first_line = re.sub(r"\(https?://[^)]*\)", "", first_line)
        w(f"/// {first_line}")
        w("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]")
        w(f"pub enum {name} {{")
        for m, v in members:
            w(f"    /// Value {v['value']}.")
            w(f"    {m},")
        w("}")
        w("")
        w(f"impl {name} {{")
        w("    /// Every member, by value.")
        w(f"    pub const ALL: [{name}; {len(members)}] = [{', '.join(f'{name}::{m}' for m, _ in members)}];")
        w("")
        w("    /// The stored value.")
        w("    pub fn value(self) -> i32 {")
        w("        match self {")
        for m, v in members:
            w(f"            {name}::{m} => {v['value']},")
        w("        }")
        w("    }")
        w("")
        w("    /// The member a stored value names, if the project names one.")
        w("    pub fn from_value(value: i32) -> Option<Self> {")
        w("        Some(match value {")
        for m, v in members:
            w(f"            {v['value']} => {name}::{m},")
        w("            _ => return None,")
        w("        })")
        w("    }")
        w("}")
        w("")
    w("/// The name of the member of the enum `enum_name` that `value` is, if the project names one.")
    w("pub fn member_name(enum_name: &str, value: i32) -> Option<&'static str> {")
    w("    Some(match (enum_name, value) {")
    for name in sorted(data):
        if name in SKIP:
            continue
        for m, v in sorted(data[name]["members"].items(), key=lambda kv: kv[1]["value"]):
            w(f'        ("{name}", {v["value"]}) => "{m}",')
    w("        _ => return None,")
    w("    })")
    w("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
